
#include <stdio.h>
#include <math.h>

/**
 * @brief Главная функция программы для обработки трех действительных чисел.
 *
 * Функция организует разветвленный процесс: запрашивает у пользователя три числа,
 * проверяет корректность ввода, а затем либо удваивает их (если выполняется
 * условие a < b < c), либо заменяет на их абсолютные значения.
 *
 * @param a первое действительное число
 * @param b второе действительное число
 * @param с третье действительное число
 *
 * @return Код завершения программы
 */
int main() {
    double a, b, c;

    printf("Введите три действительных числа (a, b, c): ");
    if (scanf("%lf %lf %lf", &a, &b, &c) != 3) {
        printf("Ошибка: нужно было ввести три числа!\n");
        return 1;
    }


    if (a < b && b < c) {
        printf("\nУсловие (a < b < c) ВЫПОЛНЯЕТСЯ. Удваиваем числа.\n");
        a = a * 2;
        b = b * 2;
        c = c * 2;
    } else {
        printf("\nУсловие (a < b < c) НЕ выполняется. Берем абсолютное значение\n");
        a = fabs(a);
        b = fabs(b);
        c = fabs(c);
    }

    printf("Результат:\n");
    printf("a = %.2lf\n", a);
    printf("b = %.2lf\n", b);
    printf("c = %.2lf\n", c);

    return 0;
}
